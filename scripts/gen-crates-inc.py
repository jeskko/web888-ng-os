"""Write web888d-crates.inc from web888-ng's Cargo.lock, in the format of
`bitbake -c update_crates web888d` (which can't write into the read-only
layer mount of scripts/kas-podman.sh).

    scripts/gen-crates-inc.py ../server/Cargo.lock \\
        > meta-web888/recipes-sdr/web888d/web888d-crates.inc
"""
import sys
import tomllib

CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index"

lock = tomllib.load(open(sys.argv[1], "rb"))
pkgs = sorted(
    (p for p in lock["package"] if p.get("source") == CRATES_IO),
    key=lambda p: (p["name"], p["version"]),
)
print("# Autogenerated from web888-ng Cargo.lock (same format as")
print("# `bitbake -c update_crates web888d`); regenerate when SRCREV changes it:")
print("# scripts/gen-crates-inc.py <web888-ng>/Cargo.lock > web888d-crates.inc")
print()
print('SRC_URI += " \\')
for p in pkgs:
    print(f"    crate://crates.io/{p['name']}/{p['version']} \\")
print('"')
print()
for p in pkgs:
    print(f'SRC_URI[{p["name"]}-{p["version"]}.sha256sum] = "{p["checksum"]}"')
